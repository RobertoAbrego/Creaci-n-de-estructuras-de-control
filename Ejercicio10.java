public class Ejercicio10 {
    public static void main(String[] args) {
        // Imprimir un triángulo de asteriscos
        for (int fila = 1; fila <= 5; fila++) {
            // Imprimir espacios antes de los asteriscos
            for (int col = 1; col <= fila; col++) {
                // Imprimir un asterisco
                System.out.print("* ");
                // Imprimir un espacio después de cada asterisco
            }
            System.out.println();
            // Imprimir una nueva línea después de cada fila
        }
    }
}
