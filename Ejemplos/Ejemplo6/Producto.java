package Ejemplos.Ejemplo6;
// Archivo: Producto.java 
public class Producto { 
    String nombre; 
    double precio; 
    public Producto(String nombre) { 
        this.nombre = nombre; 
        this.precio = 0; 
    } 
    public Producto(String nombre, double precio) { 
        this.nombre = nombre; 
        this.precio = precio; 
    } 
}